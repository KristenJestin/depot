import { Database as BunDatabase } from "bun:sqlite";
import { drizzle } from "drizzle-orm/bun-sqlite";
import { migrate } from "drizzle-orm/bun-sqlite/migrator";
import * as schema from "#/db/schema";
import path from "node:path";
import { existsSync } from "node:fs";

export type Database = ReturnType<typeof createDb>;

// ── Database factory ──────────────────────────────────────────────────────────

function createDb(client: BunDatabase) {
  return drizzle({ client, relations: schema.relations });
}

export function resolveMigrationsFolder(baseDir = __dirname): string {
  // Keep the runtime on Drizzle's standard folder layout while supporting both
  // source execution (`src/...`) and the bundled CLI (`dist/...`).
  const candidates = [
    path.resolve(baseDir, "db", "migrations"),
    path.resolve(baseDir, "..", "src", "db", "migrations"),
    path.resolve(baseDir, "migrations"),
  ];

  const found = candidates.find((candidate) => existsSync(candidate));
  if (!found) {
    throw new Error(`Could not find Drizzle migrations folder from '${baseDir}'`);
  }

  return found;
}

/**
 * Open (or create) the depot database at the given path.
 * Runs pending migrations automatically.
 * Use `":memory:"` for tests.
 */
export function openDatabase(path: string): { db: Database; client: BunDatabase } {
  const client = new BunDatabase(path);
  client.run("PRAGMA journal_mode = WAL;");
  client.run("PRAGMA busy_timeout = 5000;");
  client.run("PRAGMA foreign_keys = ON;");
  const db = createDb(client);
  // Apply unapplied SQL migrations generated by drizzle-kit.
  migrate(db, { migrationsFolder: resolveMigrationsFolder() });
  return { db, client };
}

/**
 * Resolve the default database path: `~/.depot/depot.db`.
 */
export function defaultDbPath(): string {
  const home = process.env.HOME ?? process.env.USERPROFILE ?? "";
  return `${home.replace(/\\/g, "/")}/.depot/depot.db`;
}
